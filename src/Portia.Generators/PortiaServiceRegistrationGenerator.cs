using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Cntryl.Portia;

/// <summary>
/// Generates dependency-injection registration for concrete reactors and projectors, wires each
/// into a registry its runner resolves from, registers a <c>RequestTransportRegistration</c> for
/// every routed request, and registers every request handler — all using compile-time discovery
/// instead of runtime assembly scanning or reflection. Each of these three concerns is discovered
/// and emitted independently below (see <see cref="ReactorsAndProjectors" />,
/// <see cref="RequestTransportsRegistration" />, <see cref="RequestHandlers" />) and composed only in
/// <see cref="Generate" />; registering an RPC worker per request is a separate, independent
/// concern owned entirely by <see cref="FitzRpcWorkerRegistrationGenerator" />.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class PortiaServiceRegistrationGenerator : IIncrementalGenerator
{
    const string ServiceCollectionMetadataName = "Microsoft.Extensions.DependencyInjection.IServiceCollection";
    const string ProjectorRegistrationMetadataName = "Cntryl.Portia.ProjectorRegistration";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var components = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => ReactorsAndProjectors.IsCandidate(node),
                static (syntaxContext, _) => ReactorsAndProjectors.GetRegisterableComponent(syntaxContext))
            .Where(static component => component is not null)
            .Select(static (component, _) => component!)
            .Collect();

        var requests = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => RequestTransportDiscovery.IsCandidate(node),
                static (syntaxContext, _) => RequestTransportDiscovery.GetRequestTransportComponent(syntaxContext))
            .Where(static request => request is not null)
            .Select(static (request, _) => request!)
            .Collect();

        var requestHandlers = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => RequestHandlers.IsCandidate(node),
                static (syntaxContext, _) => RequestHandlers.GetRequestHandlerTypeName(syntaxContext))
            .Where(static typeName => typeName is not null)
            .Select(static (typeName, _) => typeName!)
            .Collect();

        context.RegisterSourceOutput(
            components.Combine(requests).Combine(requestHandlers).Combine(context.CompilationProvider),
            static (sourceContext, pair) => Generate(
                sourceContext,
                pair.Left.Left.Left,
                pair.Left.Left.Right,
                pair.Left.Right,
                pair.Right));
    }

    static void Generate(
        SourceProductionContext context,
        ImmutableArray<ReactorsAndProjectors.RegisterableComponent> components,
        ImmutableArray<RequestTransportComponent> requests,
        ImmutableArray<string> requestHandlers,
        Compilation compilation)
    {
        if (components.IsDefaultOrEmpty && requests.IsDefaultOrEmpty && requestHandlers.IsDefaultOrEmpty)
            return;

        // Registration only makes sense when the consuming project actually references
        // Microsoft.Extensions.DependencyInjection; otherwise, skip silently rather than fail
        // every build of a project that has no interest in DI registration.
        if (compilation.GetTypeByMetadataName(ServiceCollectionMetadataName) is null)
            return;

        // The projector registry additionally needs Portia.Core (ProjectorRegistration,
        // ProjectorRunner); skip just that part for a project that only references
        // Portia.Abstractions.
        var canRegisterProjectors = compilation.GetTypeByMetadataName(ProjectorRegistrationMetadataName) is not null;

        var source = new StringBuilder()
            .AppendLine("// <auto-generated />")
            .AppendLine("#nullable enable")
            .AppendLine("namespace Cntryl.Portia;")
            .AppendLine()
            .AppendLine("/// <summary>")
            .AppendLine("/// Registers Portia reactors, projectors, and routed requests discovered at compile time.")
            .AppendLine("/// </summary>")
            .AppendLine("public static class PortiaGeneratedServiceCollectionExtensions")
            .AppendLine("{")
            .AppendLine("    /// <summary>")
            .AppendLine("    /// Registers every concrete reactor and projector declared in this compilation, wires")
            .AppendLine("    /// each into the registry its runner resolves from, and registers a")
            .AppendLine("    /// RequestTransportRegistration for every routed request.")
            .AppendLine("    /// </summary>")
            .AppendLine("    /// <param name=\"services\">The service collection to register into.</param>")
            .AppendLine("    /// <returns>The same service collection, for chaining.</returns>")
            .AppendLine("    public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddPortiaGeneratedComponents(")
            .AppendLine("        this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)")
            .AppendLine("    {");

        RequestHandlers.AppendRegistrations(source, requestHandlers);
        ReactorsAndProjectors.AppendRegistrations(source, components, canRegisterProjectors);
        RequestTransportsRegistration.AppendRegistrations(source, requests);

        _ = source
            .AppendLine("        return services;")
            .AppendLine("    }")
            .AppendLine("}");

        context.AddSource(
            "PortiaGeneratedServiceCollectionExtensions.g.cs",
            SourceText.From(source.ToString(), Encoding.UTF8));
    }

    /// <summary>
    /// Discovers and registers every concrete reactor and projector declared in a compilation —
    /// its own reason to change, independent of request transports or handlers.
    /// </summary>
    static class ReactorsAndProjectors
    {
        const string ProjectorMetadataName = "Cntryl.Portia.Projector`1";
        const string ReactorMetadataName = "Cntryl.Portia.Reactor";

        public static bool IsCandidate(SyntaxNode node) => node is ClassDeclarationSyntax;

        public static RegisterableComponent? GetRegisterableComponent(GeneratorSyntaxContext context)
        {
            var declaration = (ClassDeclarationSyntax)context.Node;

            if (context.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol symbol || symbol.IsAbstract)
                return null;

            if (InheritsFrom(symbol, ReactorMetadataName))
            {
                return new RegisterableComponent(
                    symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    projectionType: null);
            }

            var projectorBase = GetOpenGenericBase(symbol, ProjectorMetadataName);

            return projectorBase is not null
                ? new RegisterableComponent(
                    symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    projectorBase.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                : null;
        }

        public static void AppendRegistrations(StringBuilder source, ImmutableArray<RegisterableComponent> components, bool canRegisterProjectors)
        {
            var ordered = components
                .GroupBy(component => component.TypeName, StringComparer.Ordinal)
                .Select(group => group.First())
                .OrderBy(component => component.TypeName, StringComparer.Ordinal)
                .ToArray();

            foreach (var component in ordered)
            {
                _ = source
                    .Append("        _ = global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddTransient<")
                    .Append(component.TypeName)
                    .AppendLine(">(services);");

                if (component.ProjectionType is null)
                {
                    _ = source
                        .Append("        _ = global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton(services, new global::Cntryl.Portia.ReactorRegistration(")
                        .Append("typeof(")
                        .Append(component.TypeName)
                        .Append("), static sp => global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<")
                        .Append(component.TypeName)
                        .AppendLine(">(sp)));");
                }
                else if (canRegisterProjectors)
                {
                    _ = source
                        .Append("        _ = global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton(services, new global::Cntryl.Portia.ProjectorRegistration(")
                        .Append("typeof(")
                        .Append(component.TypeName)
                        .AppendLine("), static (runner, sp, checkpoint, options, ct) => runner.RunAsync(")
                        .Append("            global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<")
                        .Append(component.TypeName)
                        .AppendLine(">(sp), checkpoint, options, ct)));");
                }
            }
        }

        static bool InheritsFrom(INamedTypeSymbol symbol, string metadataName)
        {
            for (var current = symbol.BaseType; current is not null; current = current.BaseType)
            {
                if (current.ToDisplayString() == metadataName)
                    return true;
            }

            return false;
        }

        static INamedTypeSymbol? GetOpenGenericBase(INamedTypeSymbol symbol, string metadataName)
        {
            var expectedName = metadataName.Split('.').Last();

            for (var current = symbol.BaseType; current is not null; current = current.BaseType)
            {
                if (current.OriginalDefinition.MetadataName == expectedName
                    && current.OriginalDefinition.ContainingNamespace.ToDisplayString() == "Cntryl.Portia")
                {
                    return current;
                }
            }

            return null;
        }

        public sealed class RegisterableComponent(string typeName, string? projectionType)
        {
            public string TypeName { get; } = typeName;

            public string? ProjectionType { get; } = projectionType;
        }
    }

    /// <summary>
    /// Discovers and registers every request handler (including stream handlers and
    /// authorizers) declared in a compilation, plus the generated request bus itself — its own
    /// reason to change, independent of reactors, projectors, or request transports.
    /// </summary>
    static class RequestHandlers
    {
        const string RequestHandlerMetadataName = "IRequestHandler`1";
        const string RequestHandlerWithResultMetadataName = "IRequestHandler`2";
        const string StreamRequestHandlerMetadataName = "IStreamRequestHandler`2";
        const string RequestAuthorizerMetadataName = "IRequestAuthorizer`1";

        public static bool IsCandidate(SyntaxNode node) => node is ClassDeclarationSyntax;

        public static string? GetRequestHandlerTypeName(GeneratorSyntaxContext context)
        {
            var declaration = (ClassDeclarationSyntax)context.Node;

            if (context.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol { IsAbstract: false } symbol)
                return null;

            var isHandler = symbol.AllInterfaces.Any(iface =>
                iface.OriginalDefinition.ContainingNamespace.ToDisplayString() == "Cntryl.Portia"
                && (iface.OriginalDefinition.MetadataName == RequestHandlerMetadataName
                    || iface.OriginalDefinition.MetadataName == RequestHandlerWithResultMetadataName
                    || iface.OriginalDefinition.MetadataName == StreamRequestHandlerMetadataName
                    || iface.OriginalDefinition.MetadataName == RequestAuthorizerMetadataName));

            return isHandler ? symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) : null;
        }

        public static void AppendRegistrations(StringBuilder source, ImmutableArray<string> requestHandlers)
        {
            var ordered = requestHandlers
                .Distinct(StringComparer.Ordinal)
                .OrderBy(typeName => typeName, StringComparer.Ordinal)
                .ToArray();

            foreach (var handlerTypeName in ordered)
            {
                _ = source
                    .Append("        _ = global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddTransient<")
                    .Append(handlerTypeName)
                    .AppendLine(">(services);");
            }

            if (ordered.Length > 0)
            {
                _ = source
                    .AppendLine("        _ = global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddTransient<")
                    .AppendLine("            global::Cntryl.Portia.IRequestBus, global::Cntryl.Portia.GeneratedRequestBus>(services);");
            }
        }
    }

    /// <summary>
    /// Registers a <c>RequestTransportRegistration</c> for every routed, transport-marked
    /// request declared in a compilation — its own reason to change, independent of reactors,
    /// projectors, or request handlers. Discovery itself lives in
    /// <see cref="RequestTransportDiscovery" />, shared with
    /// <see cref="FitzRpcWorkerRegistrationGenerator" />.
    /// </summary>
    static class RequestTransportsRegistration
    {
        public static void AppendRegistrations(StringBuilder source, ImmutableArray<RequestTransportComponent> requests)
        {
            var ordered = requests
                .GroupBy(request => request.TypeName, StringComparer.Ordinal)
                .Select(group => group.First())
                .OrderBy(request => request.TypeName, StringComparer.Ordinal)
                .ToArray();

            foreach (var request in ordered)
            {
                _ = source
                    .Append("        _ = global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton(services, new global::Cntryl.Portia.RequestTransportRegistration(")
                    .Append("typeof(")
                    .Append(request.TypeName)
                    .Append("), ")
                    .Append(RequestTransportDiscovery.FormatTransports(request.Transports))
                    .Append(", new global::Cntryl.Portia.RequestRouteAttribute(")
                    .Append(RequestTransportDiscovery.FormatStringLiteral(request.Realm))
                    .Append(", ")
                    .Append(RequestTransportDiscovery.FormatStringLiteral(request.Area))
                    .Append(", ")
                    .Append(RequestTransportDiscovery.FormatStringLiteral(request.Resource))
                    .Append(", ")
                    .Append(RequestTransportDiscovery.FormatStringLiteral(request.Operation))
                    .AppendLine(")));");
            }
        }
    }
}
