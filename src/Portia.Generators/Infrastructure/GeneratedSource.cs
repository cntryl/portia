using System.Collections.Immutable;
using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Cntryl.Portia;

static class GeneratedSource
{
    public static ImmutableArray<GeneratedFile> Capture(Action<GeneratedOutput> generate, CancellationToken ct)
    {
        var output = new GeneratedOutput(ct);
        generate(output);
        return output.Files.ToImmutableArray();
    }

    public static void Add(GeneratedOutput output, string hintName, string source) =>
        output.Files.Add(new GeneratedFile(hintName, source));

    public static string Identity(string value)
    {
        using var algorithm = SHA256.Create();
        var bytes = algorithm.ComputeHash(Encoding.UTF8.GetBytes(value));
        var characters = new char[bytes.Length * 2];
        const string hexadecimal = "0123456789abcdef";
        for (var index = 0; index < bytes.Length; index++)
        {
            characters[index * 2] = hexadecimal[bytes[index] >> 4];
            characters[index * 2 + 1] = hexadecimal[bytes[index] & 15];
        }
        return new(characters);
    }

    public static string Label(string value) => new(value.Where(character => char.IsLetterOrDigit(character)
        || character == '_').Take(64).ToArray());

    public static void Add(SourceProductionContext context, string hintName, string source)
    {
        context.CancellationToken.ThrowIfCancellationRequested();
        context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
    }

    public static void AddFormatted(SourceProductionContext context, string hintName, string source)
    {
        var root = CSharpSyntaxTree.ParseText(source, cancellationToken: context.CancellationToken)
            .GetRoot(context.CancellationToken);
        context.AddSource(hintName, SourceText.From(root.NormalizeWhitespace(eol: "\n").ToFullString() + "\n", Encoding.UTF8));
    }

    public static IEnumerable<(string Key, T[] Items)> Buckets<T>(IEnumerable<T> items,
        Func<T, string> identity, CancellationToken ct)
    {
        var keyed = items.Select(item => (Key: identity(item), Item: item))
            .GroupBy(entry => entry.Key, StringComparer.Ordinal).Select(group => group.First())
            .OrderBy(entry => entry.Key, StringComparer.Ordinal)
            .Select(entry =>
            {
                ct.ThrowIfCancellationRequested();
                return (Key: Identity(entry.Key), Identity: entry.Key, entry.Item);
            }).ToArray();
        return Partition(keyed, string.Empty, ct);
    }

    public static string StatementTree(GeneratedOutput context, string space, string className,
        string method, string parameterType, string parameterName, string[] statements, string hint, bool internalMethods = false)
    {
        var leaves = Buckets(statements, statement => statement, context.CancellationToken)
            .ToDictionary(bucket => bucket.Key, bucket => bucket.Items, StringComparer.Ordinal);
        var nodes = new HashSet<string>(StringComparer.Ordinal) { string.Empty };
        foreach (var key in leaves.Keys)
            for (var length = 1; length <= key.Length; length++)
                _ = nodes.Add(key.Substring(0, length));
        var children = nodes.Where(key => key.Length > 0).GroupBy(key => key.Substring(0, key.Length - 1), StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.OrderBy(key => key, StringComparer.Ordinal).ToArray(), StringComparer.Ordinal);
        foreach (var key in nodes.OrderBy(key => key, StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            var source = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace ")
                .Append(space).Append(";\n\ninternal static partial class ").Append(className).Append("\n{\n")
                .Append(internalMethods ? "    internal static void " : "    private static void ").Append(method).Append("_Bucket").Append(key)
                .Append('(').Append(parameterType).Append(' ').Append(parameterName).AppendLine(")\n    {");
            if (leaves.TryGetValue(key, out var body))
            {
                foreach (var statement in body)
                    source.Append("        ").AppendLine(statement);
            }
            else
            {
                foreach (var child in children[key])
                    source.Append("        ").Append(method).Append("_Bucket").Append(child).Append('(').Append(parameterName).AppendLine(");");
            }
            source.AppendLine("    }").AppendLine("}");
            Add(context, hint + "." + (key.Length == 0 ? "Root" : key) + ".g.cs", source.ToString());
        }
        return method + "_Bucket";
    }

    static IEnumerable<(string Key, T[] Items)> Partition<T>((string Key, string Identity, T Item)[] entries,
        string prefix, CancellationToken ct)
    {
        ct.ThrowIfCancellationRequested();
        if (entries.Length <= 128)
        {
            yield return (prefix, entries.Select(entry => entry.Item).ToArray());
            yield break;
        }

        foreach (var group in entries.GroupBy(entry => BucketCharacter(entry.Key, entry.Identity, prefix.Length))
                     .OrderBy(group => group.Key))
        {
            foreach (var bucket in Partition(group.ToArray(), prefix + group.Key, ct))
                yield return bucket;
        }
    }

    static char BucketCharacter(string hash, string identity, int depth)
    {
        if (depth < hash.Length)
            return hash[depth];
        // Read identity nibbles only if a digest collision requires further subdivision.
        var offset = depth - hash.Length;
        var index = offset / 4;
        return index >= identity.Length ? '_' : "0123456789abcdef"[(identity[index] >> ((3 - offset % 4) * 4)) & 15];
    }
}

sealed record GeneratedFile(string HintName, string Source);

sealed class GeneratedOutput(CancellationToken cancellationToken)
{
    public CancellationToken CancellationToken { get; } = cancellationToken;
    public List<GeneratedFile> Files { get; } = [];
}
